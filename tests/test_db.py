def head_revision() -> str | None:
    return ScriptDirectory.from_config(alembic_config()).get_current_head()


def make_target(session, branch="master") -> Target:
    target = Target(branch=branch, schedule="0 1 * * *", enabled=True)
    session.add(target)
    session.flush()
    return target


def make_run(session, target_id: int) -> Run:
    run = Run(
        uid=uuid.uuid4(),
        target_id=target_id,
        status=RunStatus.QUEUED,
        trigger=RunTrigger.SCHEDULE,
        testrig_ref="v1.0.0",
    )
    session.add(run)
    session.flush()
    return run


def make_test_case(
    session, run: Run, package="pkg", classname="tests.test_mod", name="test_something"
) -> TestCase:
    case = TestCase(
        package=package,
        classname=classname,
        name=name,
        key_hash=case_key(package, classname, name),
        first_seen_run_id=run.id,
    )
    session.add(case)
    session.flush()
    return case


def test_migrations_create_schema_at_head(session):
    tables = set(inspect(session.get_bind()).get_table_names())
    assert {
        "target",
        "run",
        "package_result",
        "test_case",
        "test_result",
        "alembic_version",
    } <= tables

    revision = session.execute(text("SELECT version_num FROM alembic_version")).scalar_one()
    assert revision == head_revision()


def test_upgrading_twice_is_a_noop(engine):
    with engine.begin() as connection:
        before, after = run_migrations(connection)

    assert before == after == head_revision()


