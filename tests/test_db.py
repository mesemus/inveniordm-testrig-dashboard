def test_migration_0002_backfills_existing_test_cases(engine):
    # Postgres DDL is transactional: downgrade, insert, upgrade, check, then roll it all back.
    with engine.connect() as connection:
        transaction = connection.begin()
        try:
            config = alembic_config(connection)
            command.downgrade(config, "0001")
            target_id = connection.execute(
                text(
                    "INSERT INTO target (branch, schedule, enabled) "
                    "VALUES ('m', '0 1 * * *', true) RETURNING id"
                )
            ).scalar_one()
            run_id = connection.execute(
                text(
                    "INSERT INTO run (uid, target_id, status, trigger, testrig_ref) "
                    "VALUES (:uid, :target, 'queued', 'schedule', 'v1') RETURNING id"
                ),
                {"uid": uuid.uuid4(), "target": target_id},
            ).scalar_one()
            connection.execute(
                text(
                    "INSERT INTO test_case (package, classname, name, first_seen_run_id) "
                    "VALUES ('pkg', 'tests.t', :name, :run)"
                ),
                {"name": "test_é[ü]", "run": run_id},
            )

            command.upgrade(config, "head")

            stored = connection.execute(text("SELECT key_hash FROM test_case")).scalar_one()
            assert bytes(stored) == case_key("pkg", "tests.t", "test_é[ü]")
        finally:
            transaction.rollback()


class _BrokenUnlockConnection:
    def __enter__(self):
        return self

    def __exit__(self, *args):
        return False

    def execution_options(self, **kwargs):
        return self

    def scalar(self, statement):
        return True

    def execute(self, statement):
        raise RuntimeError("unlock failed")


class _BrokenUnlockEngine:
    def connect(self):
        return _BrokenUnlockConnection()


def test_advisory_lock_unlock_failure_does_not_hide_the_block_error():
    with pytest.raises(ValueError, match="boom"):
        with db.try_advisory_lock(_BrokenUnlockEngine(), 1):
            raise ValueError("boom")


